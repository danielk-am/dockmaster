// The WPDS app-family contract, Localhost Manager edition: the invariants that
// make Localhost Manager part of the family (Prosper, Thrive, Snippet Manager)
// rather than a drifting one-off. Mirrors src/family-ui-contract.test.js
// in the Prosper repo, adapted to what Localhost Manager composes today;
// family-shell.mjs keeps the deeper per-surface checks. When an assertion
// here fails, the question is not how to silence it but whether the family
// contract deliberately moved, and if it did, every app in the family
// moves with it.
//
// Named gaps, the unification frontier, documented rather than asserted:
// - documentation-surface: Prosper routes /docs/changelog, /docs/readme,
//   and /docs/api; Snippet Manager keeps a footer docs row. Localhost Manager
//   points at README.md from Overview prose and has no in-app
//   documentation surface yet.
// - rotating-hero: Prosper's overview rotates HERO_VARIANTS on an
//   interval; Localhost Manager's overview hero is static.
// - flush-white-shell: Prosper and Snippet Manager run the flush white
//   shell (canvas and surface both #fff). Localhost Manager deliberately keeps
//   the waypoint style (gray canvas, white surface, data-app-style
//   "waypoint"); that current choice is what the shell block below pins.
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';

const app = await readFile(new URL('../src/App.jsx', import.meta.url), 'utf8');
const assistant = await readFile(new URL('../src/AssistantPanel.jsx', import.meta.url), 'utf8');
const css = await readFile(new URL('../src/style.css', import.meta.url), 'utf8');
const html = await readFile(new URL('../index.html', import.meta.url), 'utf8');
const pkg = JSON.parse(await readFile(new URL('../package.json', import.meta.url), 'utf8'));

// Vendors the shared family packages, pinned by file.
assert.match(pkg.dependencies['@1dr0/ai-chat'], /^file:vendor\//, '@1dr0/ai-chat is vendored by file');
assert.match(pkg.dependencies['@1dr0/wpds-identity'], /^file:vendor\//, '@1dr0/wpds-identity is vendored by file');

// Uses the waypoint shell and the shared resize handles.
assert.ok(css.includes('--ps-canvas: #f7f8fa;'), 'waypoint gray canvas token');
assert.ok(css.includes('--ps-surface: #fff;'), 'white surface token');
assert.ok(html.includes('data-app-style="waypoint"'), 'declares the waypoint app style');
assert.ok(app.includes("import { AiChatResizeHandle, PopoverSelect } from '@1dr0/ai-chat';"), 'shell primitives come from @1dr0/ai-chat');
assert.match(app, /<AiChatResizeHandle[\s\S]*?edge="right"/, 'sidebar resizes through the shared handle');
assert.match(assistant, /<AiChatResizeHandle[\s\S]*?edge="left"/, 'assistant resizes through the shared handle');

// Derives identity from the shared package, never hand-drawn marks.
assert.ok(app.includes("generatedIdentityImage('mark', 'Localhost Manager')"), 'app mark is generated by @1dr0/wpds-identity');
assert.ok(app.includes('mountEditableProfilePage'), 'profile page mounts through the shared package');
assert.ok(app.includes("from '@1dr0/wpds-identity'"), 'identity imports come from the shared package');

// Keeps the family support surface in the shell (see documentation-surface gap).
assert.ok(app.includes('Help &amp; Feedback'), 'Help & Feedback utility in the shell');
assert.ok(app.includes('Version {VERSION}'), 'running version in the footer');

// Uses the quick-start overview journeys.
assert.ok(app.includes('ps-overview__hero'), 'overview keeps the hero section');
assert.ok(app.includes('<p className="ps-eyebrow">Quick Start</p>'), 'overview leads with Quick Start journeys');

// Routes dropdowns through the shared popover select.
assert.ok(app.includes('<PopoverSelect'), 'dropdowns use the shared popover select');
assert.ok(!app.includes('SelectControl'), 'no raw SelectControl');
assert.doesNotMatch(app, /<select\b/i, 'no raw select element');

console.log('family-ui-contract: ok');
